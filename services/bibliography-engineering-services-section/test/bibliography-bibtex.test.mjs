import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { test } from "node:test";
import { projectBibtex } from "../src/bibliography-bibtex.mjs";

function triple(citekey, reference, path) { return { citekey, reference, path }; }

test("projectBibtex maps eprint to eprinttype: arxiv when eprinttype is absent", () => {
  const bib = projectBibtex({
    triples: [triple("aksoy2025", { authors: ["Aksoy, Sinan G."], title: "Re-imagining Spectral Graph Theory", year: 2025, eprint: "2504.10624" }, "a.md")],
    carriers: [],
  });
  assert.match(bib, /eprint = \{2504\.10624\}/u);
  assert.match(bib, /eprinttype = \{arxiv\}/u);
});

test("projectBibtex is byte-identical across two runs over the same input", () => {
  const collected = {
    triples: [
      triple("wolf2025", { authors: ["Wolf, B"], title: "Generalized graphs", year: 2025 }, "a.md"),
      triple("aksoy2025", { authors: ["Aksoy, Sinan G.", "Young, Stephen J."], title: "Re-imagining Spectral Graph Theory", year: 2025, eprint: "2504.10624", eprinttype: "arxiv" }, "b.md"),
    ],
    carriers: [],
  };
  const first = projectBibtex(collected);
  const second = projectBibtex(collected);
  assert.equal(first, second);
  assert.equal(createHash("sha256").update(first).digest("hex"), createHash("sha256").update(second).digest("hex"));
});

test("projectBibtex sorts entries by citekey regardless of input order", () => {
  const bib = projectBibtex({
    triples: [
      triple("zed2020", { authors: ["Zed, A"], title: "Last", year: 2020 }, "a.md"),
      triple("aaron2020", { authors: ["Aaron, A"], title: "First", year: 2020 }, "b.md"),
    ],
    carriers: [],
  });
  const firstIndex = bib.indexOf("aaron2020");
  const lastIndex = bib.indexOf("zed2020");
  assert.ok(firstIndex > -1 && lastIndex > -1 && firstIndex < lastIndex);
});

test("projectBibtex prefers the depth-2 carrier's own fields over a conflicting inline reference", () => {
  const bib = projectBibtex({
    triples: [triple("euler1736", { authors: ["Euler, Leonhard"], title: "Wrong title", year: 1736 }, "a.md")],
    carriers: [{ citekey: "euler1736", path: "bibliographies/euler1736.md", recognized: { admitted: true, key: "euler1736", authors: ["Euler, Leonhard"], title: "Solutio problematis ad geometriam situs pertinentis", year: 1736, referenceType: "article" } }],
  });
  assert.match(bib, /Solutio problematis/u);
  assert.ok(!bib.includes("Wrong title"));
});

test("projectBibtex opens with a generated-artifact header comment", () => {
  const bib = projectBibtex({ triples: [], carriers: [] });
  assert.match(bib, /^% Generated by/u);
  assert.match(bib, /Do not edit by hand/u);
});
